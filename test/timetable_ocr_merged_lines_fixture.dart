OcrWord w(String text, double left, double top, double right, double bottom) =>
    OcrWord(text, OcrBox(left, top, right, bottom));

OcrLine l(String text, double left, double top, double right, double bottom,
        List<OcrWord> words) =>
    OcrLine(text, OcrBox(left, top, right, bottom), words: words);

/// A table every divider of which is drawn.
TableLattice ruled(List<int> xs, List<int> ys) => TableLattice(
      xs: xs,
      ys: ys,
      dividedRight: <List<bool>>[
        for (int r = 0; r + 1 < ys.length; r++)
          <bool>[for (int c = 0; c + 2 < xs.length; c++) true],
      ],
      dividedBelow: <List<bool>>[
        for (int r = 0; r + 2 < ys.length; r++)
          <bool>[for (int c = 0; c + 1 < xs.length; c++) true],
      ],
    );

